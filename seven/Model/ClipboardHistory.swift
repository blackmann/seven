import AppKit
import CryptoKit
import UniformTypeIdentifiers

struct ClipboardRepresentation: Codable, Equatable, Sendable {
    let type: String
    let data: Data
}

struct ClipboardItemSnapshot: Codable, Equatable, Sendable {
    let representations: [ClipboardRepresentation]
}

struct ClipboardEntry: Identifiable, Codable, Equatable, Sendable {
    enum Kind: String, Codable { case text, image, files, other }
    let id: UUID
    let fingerprint: String
    let items: [ClipboardItemSnapshot]
    let kind: Kind
    let text: String?
    let title: String
    let sourceName: String?
    let sourceBundleIdentifier: String?
    var copiedAt: Date

    var byteCount: Int { items.reduce(0) { $0 + $1.representations.reduce(0) { $0 + $1.data.count } } }
    var searchText: String { [text, title, sourceName, sourceBundleIdentifier].compactMap { $0 }.joined(separator: " ") }
    var detail: String {
        [String((text ?? title).prefix(4000)), sourceName, copiedAt.formatted(date: .abbreviated, time: .shortened)].compactMap { $0 }.joined(separator: "\n\n")
    }
    var image: NSImage? {
        guard kind == .image else { return nil }
        for representation in items.flatMap(\.representations) {
            if UTType(representation.type)?.conforms(to: .image) == true,
               let image = NSImage(data: representation.data) { return image }
        }
        return nil
    }
}

@MainActor
final class ClipboardHistory: ObservableObject {
    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.TransientType", "org.nspasteboard.ConcealedType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "com.typeit4me.clipping", "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type", "net.antelle.keeweb"
    ]
    static var defaultStorageURL: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("seven", isDirectory: true).appendingPathComponent("clipboard-history.json")
    }

    @Published private(set) var entries: [ClipboardEntry] = []
    @Published var isPaused = false {
        didSet { defaults?.set(isPaused, forKey: "clipboardRecordingPaused"); lastChangeCount = pasteboard.changeCount }
    }
    @Published var pasteAutomatically = false {
        didSet { defaults?.set(pasteAutomatically, forKey: "clipboardPasteAutomatically") }
    }
    @Published private(set) var storageError: String?
    private let pasteboard: NSPasteboard
    private let storageURL: URL?
    private let defaults: UserDefaults?
    private let limit: Int
    private let maximumBytes: Int
    private let maximumEntryBytes: Int
    private let writer = DispatchQueue(label: "seven.clipboard-history", qos: .utility)
    private var timer: Timer?
    private var lastChangeCount: Int
    private var thumbnails: [UUID: NSImage] = [:]

    init(storageURL: URL?, pasteboard: NSPasteboard = .general, limit: Int = 200,
         maximumBytes: Int = 64 * 1024 * 1024, maximumEntryBytes: Int = 16 * 1024 * 1024,
         autoStart: Bool = true, defaults: UserDefaults? = .standard) {
        self.storageURL = storageURL
        self.pasteboard = pasteboard
        self.limit = max(1, limit)
        self.maximumBytes = maximumBytes
        self.maximumEntryBytes = maximumEntryBytes
        self.defaults = defaults
        lastChangeCount = pasteboard.changeCount
        isPaused = defaults?.bool(forKey: "clipboardRecordingPaused") ?? false
        pasteAutomatically = defaults?.bool(forKey: "clipboardPasteAutomatically") ?? false
        if let storageURL, FileManager.default.fileExists(atPath: storageURL.path) {
            do {
                let data = try Data(contentsOf: storageURL)
                entries = try JSONDecoder().decode([ClipboardEntry].self, from: data)
                    .sorted { $0.copiedAt > $1.copiedAt }
                trim()
            } catch { storageError = "Couldn’t load clipboard history." }
        }
        if autoStart { start() }
    }

    func start() {
        guard timer == nil else { return }
        lastChangeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.captureIfChanged() }
        }
        timer.tolerance = 0.1
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() { timer?.invalidate(); timer = nil }

    func captureIfChanged(sourceName: String? = nil, sourceBundleIdentifier: String? = nil) {
        guard pasteboard.changeCount != lastChangeCount else { return }
        let changeCount = pasteboard.changeCount
        lastChangeCount = changeCount
        guard !isPaused else { return }
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard Self.ignoredTypes.isDisjoint(with: types), let items = pasteboard.pasteboardItems, !items.isEmpty,
              items.allSatisfy({ Self.ignoredTypes.isDisjoint(with: Set($0.types.map(\.rawValue))) }) else { return }

        var byteCount = 0
        var snapshots: [ClipboardItemSnapshot] = []
        for item in items {
            var representations: [ClipboardRepresentation] = []
            for type in item.types where Self.isSupported(type) {
                guard let data = item.data(forType: type) else { continue }
                byteCount += data.count
                guard byteCount <= maximumEntryBytes else { return }
                representations.append(ClipboardRepresentation(type: type.rawValue, data: data))
            }
            if !representations.isEmpty { snapshots.append(ClipboardItemSnapshot(representations: representations)) }
        }
        guard !snapshots.isEmpty, pasteboard.changeCount == changeCount else { return }

        let fileURLs = items.compactMap { $0.string(forType: .fileURL) }.compactMap(URL.init(string:))
        let text = items.compactMap { item -> String? in
            if let plain = item.string(forType: .string) { return plain }
            if let url = item.string(forType: .URL) { return url }
            if let rtf = item.data(forType: .rtf) {
                return try? NSAttributedString(data: rtf, options: [.documentType: NSAttributedString.DocumentType.rtf], documentAttributes: nil).string
            }
            return nil
        }.joined(separator: "\n")
        let imageItems = Self.imagePayload(in: snapshots, maximumBytes: maximumEntryBytes)
        if let imageItems { snapshots = imageItems }
        let hasImage = imageItems != nil
        let kind: ClipboardEntry.Kind = hasImage ? .image : !fileURLs.isEmpty ? .files : !text.isEmpty ? .text : .other
        if kind == .other, items.contains(where: { $0.types.contains(.string) }), text.isEmpty { return }
        // Type-only marker changes and empty strings are not useful history items.
        guard kind != .other || snapshots.contains(where: { $0.representations.contains { !$0.data.isEmpty && $0.type != NSPasteboard.PasteboardType.string.rawValue } }) else { return }
        let title: String
        if !fileURLs.isEmpty {
            title = fileURLs.map(\.lastPathComponent).joined(separator: ", ")
        } else if hasImage { title = "Image" }
        else if !text.isEmpty { title = String(text.split(whereSeparator: \.isWhitespace).joined(separator: " ").prefix(300)) }
        else { title = "Formatted content" }
        let fingerprint: String
        if kind == .text { fingerprint = Self.digest(Data(("text:" + text).utf8)) }
        else {
            var hasher = SHA256()
            for snapshot in snapshots {
                hasher.update(data: Data([0]))
                for representation in snapshot.representations.sorted(by: { $0.type < $1.type }) {
                    hasher.update(data: Data(representation.type.utf8)); hasher.update(data: Data([0]))
                    hasher.update(data: representation.data)
                }
            }
            fingerprint = hasher.finalize().map { String(format: "%02x", $0) }.joined()
        }
        let previous = entries.first { $0.fingerprint == fingerprint }
        let source = NSWorkspace.shared.frontmostApplication
        let entry = ClipboardEntry(id: previous?.id ?? UUID(), fingerprint: fingerprint, items: snapshots,
                                   kind: kind, text: text.isEmpty ? nil : text, title: title,
                                   sourceName: sourceName ?? source?.localizedName,
                                   sourceBundleIdentifier: sourceBundleIdentifier ?? source?.bundleIdentifier, copiedAt: Date())
        entries = [entry] + entries.filter { $0.fingerprint != fingerprint }
        thumbnails[entry.id] = nil
        trim()
        persist()
    }

    func results(for query: String, in snapshot: [ClipboardEntry]? = nil) -> [ClipboardEntry] {
        let entries = snapshot ?? self.entries
        let terms = Self.folded(query).split(whereSeparator: \.isWhitespace)
        guard !terms.isEmpty else { return entries }
        return entries.filter { entry in
            let searchable = Self.folded(entry.searchText)
            return terms.allSatisfy { searchable.contains($0) }
        }
    }

    @discardableResult
    func restore(_ entry: ClipboardEntry, plainText: Bool = false) -> Bool {
        let items: [NSPasteboardItem]
        if plainText {
            guard let text = entry.text else { return false }
            let item = NSPasteboardItem(); item.setString(text, forType: .string); items = [item]
        } else {
            let snapshots = Self.imagePayload(in: entry.items, maximumBytes: maximumEntryBytes) ?? entry.items
            items = snapshots.map { snapshot in
                let item = NSPasteboardItem()
                for representation in snapshot.representations {
                    item.setData(representation.data, forType: NSPasteboard.PasteboardType(representation.type))
                }
                return item
            }
        }
        guard !items.isEmpty else { return false }
        pasteboard.clearContents()
        let success = pasteboard.writeObjects(items)
        lastChangeCount = pasteboard.changeCount
        if success, let index = entries.firstIndex(where: { $0.id == entry.id }) {
            var recent = entries[index]; recent.copiedAt = Date()
            entries = [recent] + entries.filter { $0.id != recent.id }
            persist()
        }
        return success
    }

    func delete(_ entry: ClipboardEntry) {
        entries.removeAll { $0.id == entry.id }; thumbnails[entry.id] = nil; persist()
    }

    func clear() { entries = []; thumbnails = [:]; persist() }

    func thumbnail(for entry: ClipboardEntry) -> NSImage? {
        if let cached = thumbnails[entry.id] { return cached }
        let fileImage = Self.imagePayload(in: entry.items, maximumBytes: maximumEntryBytes)?.first?.representations.first.flatMap { NSImage(data: $0.data) }
        guard let image = entry.image ?? fileImage else { return nil }
        let preview = NSImage(size: NSSize(width: 40, height: 40))
        preview.lockFocus()
        let scale = min(40 / max(image.size.width, 1), 40 / max(image.size.height, 1))
        let size = NSSize(width: image.size.width * scale, height: image.size.height * scale)
        image.draw(in: NSRect(x: (40 - size.width) / 2, y: (40 - size.height) / 2, width: size.width, height: size.height))
        preview.unlockFocus()
        thumbnails[entry.id] = preview
        return preview
    }

    func flush() { writer.sync {} }

    private static func imagePayload(in items: [ClipboardItemSnapshot], maximumBytes: Int) -> [ClipboardItemSnapshot]? {
        let representations = items.flatMap(\.representations)
        let files = representations.filter { $0.type == NSPasteboard.PasteboardType.fileURL.rawValue }
            .compactMap { String(data: $0.data, encoding: .utf8) }.compactMap(URL.init(string:))
        if files.count > 1 { return nil }
        if let file = files.first {
            guard file.isFileURL, let type = UTType(filenameExtension: file.pathExtension), type.conforms(to: .image) else { return nil }
            let size = (try? file.resourceValues(forKeys: [.fileSizeKey]))?.fileSize ?? Int.max
            if size <= maximumBytes, let data = try? Data(contentsOf: file) {
                let png = type == .png ? data : NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:])
                let image = png.flatMap { $0.count <= maximumBytes ? ClipboardRepresentation(type: NSPasteboard.PasteboardType.png.rawValue, data: $0) : nil }
                    ?? ClipboardRepresentation(type: type.identifier, data: data)
                return [ClipboardItemSnapshot(representations: [image])]
            }
        }
        let images = items.compactMap { item -> ClipboardItemSnapshot? in
            let images = item.representations.filter { UTType($0.type)?.conforms(to: .image) == true }
            return images.isEmpty ? nil : ClipboardItemSnapshot(representations: images)
        }
        return images.isEmpty ? nil : images
    }

    private func trim() {
        var bytes = 0
        entries = Array(entries.prefix(limit).prefix { entry in
            bytes += entry.byteCount
            return bytes <= maximumBytes
        })
        let ids = Set(entries.map(\.id))
        thumbnails = thumbnails.filter { ids.contains($0.key) }
    }

    private func persist() {
        guard let storageURL else { return }
        let snapshot = entries
        writer.async { [weak self] in
            do {
                let manager = FileManager.default
                try manager.createDirectory(at: storageURL.deletingLastPathComponent(), withIntermediateDirectories: true,
                                            attributes: [.posixPermissions: 0o700])
                let data = try JSONEncoder().encode(snapshot)
                try data.write(to: storageURL, options: [.atomic])
                try manager.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storageURL.path)
                DispatchQueue.main.async { self?.storageError = nil }
            } catch {
                DispatchQueue.main.async { self?.storageError = "Clipboard history couldn’t be saved." }
            }
        }
    }

    private static func isSupported(_ type: NSPasteboard.PasteboardType) -> Bool {
        if [NSPasteboard.PasteboardType.string, .rtf, .rtfd, .html, .png, .tiff, .pdf, .fileURL, .URL].contains(type) { return true }
        guard let uniform = UTType(type.rawValue) else { return false }
        return uniform.conforms(to: .text) || uniform.conforms(to: .image) || uniform.conforms(to: .url)
    }
    private static func folded(_ text: String) -> String { text.folding(options: [.caseInsensitive, .diacriticInsensitive], locale: .current) }
    private static func digest(_ data: Data) -> String { SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined() }
}
